    private function seedVark(): void
    {
        $assessment = Assessment::updateOrCreate(
            ['slug' => 'vark'],
            [
                'name_fa'                 => 'آزمون سبک یادگیری VARK',
                'description_fa'          => 'با پاسخ به ۱۶ سوال موقعیتی، سبک یادگیری شما (دیداری، شنیداری، خواندنی‌نوشتاری، حرکتی) مشخص می‌شود. در هر سوال می‌توانید چند گزینه را انتخاب کنید.',
                'kind'                    => Assessment::KIND_VARK,
                'question_type'           => 'vark_multi',
                'is_active'               => true,
                'is_required'             => true,
                'display_order'           => 2,
                'audience'                => Assessment::AUDIENCE_STUDENT,
                'expected_question_count' => 16,
            ]
        );

        $pool = $this->varkQuestionPool();

        foreach ($pool as $idx => $item) {
            $order = $idx + 1;
            $q = AssessmentQuestion::updateOrCreate(
                ['assessment_id' => $assessment->id, 'order' => $order],
                [
                    'question_text_fa' => $item['stem'],
                    'type'             => AssessmentQuestion::TYPE_VARK_MULTI,
                    'scoring_meta'     => null,
                    'is_active'        => true,
                ]
            );
            $q->options()->delete();
            $optOrder = 1;
            foreach (['V', 'A', 'R', 'K'] as $modality) {
                AssessmentQuestionOption::create([
                    'question_id' => $q->id,
                    'order'       => $optOrder++,
                    'label_fa'    => $item[$modality],
                    'value'       => $modality,
                    'weights'     => [$modality => 1],
                ]);
            }
        }
    }

