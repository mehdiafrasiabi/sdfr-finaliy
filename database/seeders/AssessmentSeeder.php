                'name_fa'                 => 'آزمون شخصیت‌شناسی MBTI',
                'description_fa'          => 'با پاسخ به ۶۴ سوال، تیپ شخصیتی شما (یکی از ۱۶ تیپ MBTI) مشخص می‌شود.',
                'kind'                    => Assessment::KIND_MBTI,
                'question_type'           => 'mbti_binary',
                'is_active'               => true,
                'is_required'             => true,
                'display_order'           => 1,
                'audience'                => Assessment::AUDIENCE_STUDENT,
                'expected_question_count' => 64,
            ]
        );

        $axes = [
            'EI' => ['a_pole' => 'E', 'b_pole' => 'I'],
            'SN' => ['a_pole' => 'S', 'b_pole' => 'N'],
            'TF' => ['a_pole' => 'T', 'b_pole' => 'F'],
            'JP' => ['a_pole' => 'J', 'b_pole' => 'P'],
        ];

        $pool = $this->mbtiQuestionPool();
        $order = 0;

        foreach ($axes as $axis => $poles) {
            foreach ($pool[$axis] as $pair) {
                $order++;
                $q = AssessmentQuestion::updateOrCreate(
                    ['assessment_id' => $assessment->id, 'order' => $order],
                    [
                        'question_text_fa' => $pair['stem'],
                        'type'             => AssessmentQuestion::TYPE_MBTI_BINARY,
                        'scoring_meta'     => ['axis' => $axis, 'a_pole' => $poles['a_pole'], 'b_pole' => $poles['b_pole']],
                        'is_active'        => true,
                    ]
                );
                $q->options()->delete();
                AssessmentQuestionOption::create([
                    'question_id' => $q->id, 'order' => 1, 'value' => 'A',
                    'label_fa'    => $pair['a'], 'weights' => [$poles['a_pole'] => 1],
                ]);
                AssessmentQuestionOption::create([
                    'question_id' => $q->id, 'order' => 2, 'value' => 'B',
                    'label_fa'    => $pair['b'], 'weights' => [$poles['b_pole'] => 1],
                ]);
            }
        }
    }

